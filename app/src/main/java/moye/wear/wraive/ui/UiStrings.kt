import androidx.compose.runtime.Composable
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.platform.LocalConfiguration
import java.util.Locale

val LocalUiLocaleTag = staticCompositionLocalOf { "system" }

@Composable
fun tr(text: String): String {
    val configured = LocalUiLocaleTag.current
    val systemLanguage = LocalConfiguration.current.locales[0]?.language ?: Locale.getDefault().language
    val language = if (configured == "system") systemLanguage else configured.substringBefore('-')
    return if (language == "zh") text else english(text)
}

