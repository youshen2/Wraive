private fun english(text: String): String {
    englishStrings[text]?.let { return it }
    return when {
        text.startsWith("管理 ") -> "Manage ${text.removePrefix("管理 ")}"
        text.startsWith("附件 · ") -> "Attachment · ${text.removePrefix("附件 · ")}"
        text.startsWith("上次同步 ") -> "Last synced ${text.removePrefix("上次同步 ")}"
        text.startsWith("质量 · ") -> "Quality · ${text.removePrefix("质量 · ")}"
        text.contains(" 个模型") -> text.replace(" 个模型", " models")
        text.contains(" 次请求") || text.contains(" 条消息") || text.contains(" 个会话") -> text
            .replace("次请求", "requests")
            .replace("条消息", "messages")
            .replace("个会话", "conversations")
        text.startsWith("活跃 ") -> text.replace("活跃 ", "Active ").replace(" 天 · 失败 ", " days · ").replace(" 次", " failures")
        text.startsWith("输入 ") && text.contains("输出") -> text
            .replace("输入 ", "Input ").replace("输出 ", "Output ").replace("缓存 ", "Cached ")
        text.contains(" 次 · ") && text.contains("tokens") -> text.replace(" 次 · ", " requests · ")
        text.startsWith("已获取 ") -> text.replace("已获取 ", "Fetched ").replace(" 个模型", " models")
        else -> text
    }
}
